import { MapData, MapId, PlatformBox } from '../types';

function makePerimeterWalls(
  prefix: string,
  w: number,
  h: number,
  d: number,
  style: PlatformBox['style']
): PlatformBox[] {
  const wallH = h + 4;
  const wallY = wallH * 0.5 - 1.5;
  const t = 2.0;
  return [
    { id: `${prefix}_wl`, x: -w * 0.5 - t * 0.5, y: wallY, z: 0, w: t, h: wallH, d: d + t * 2, style, boundary: true },
    { id: `${prefix}_wr`, x: w * 0.5 + t * 0.5, y: wallY, z: 0, w: t, h: wallH, d: d + t * 2, style, boundary: true },
    { id: `${prefix}_wn`, x: 0, y: wallY, z: -d * 0.5 - t * 0.5, w: w + t * 2, h: wallH, d: t, style, boundary: true },
    { id: `${prefix}_ws`, x: 0, y: wallY, z: d * 0.5 + t * 0.5, w: w + t * 2, h: wallH, d: t, style, boundary: true },
  ];
}

